#!/usr/bin/env python3
"""Regenerates the prototype's local assets from the app's own files, so the
design uses exactly what the app bundles and opens from file:// with no server:

  fonts.css  Inter, JetBrains Mono and the Phosphor subset as data URIs
  icons.js   the icon constants of crates/ternarywire-app/src/icons.rs

Run from anywhere: python3 design/redesign/build-assets.py
"""
import base64, os, re

HERE = os.path.dirname(os.path.abspath(__file__))
APP = os.path.join(HERE, "..", "..", "crates", "ternarywire-app")
FONTS = os.path.join(APP, "assets", "fonts")

faces = [
    ("Inter", 400, "Inter-Regular.ttf"),
    ("Inter", 500, "Inter-Medium.ttf"),
    ("Inter", 600, "Inter-SemiBold.ttf"),
    ("JBMono", 400, "JetBrainsMono-Regular.ttf"),
    ("Phosphor", 400, "Phosphor.ttf"),
]
css = ["/* Generated by build-assets.py from crates/ternarywire-app/assets/fonts. Do not edit. */"]
for family, weight, name in faces:
    data = base64.b64encode(open(os.path.join(FONTS, name), "rb").read()).decode()
    css.append(f'@font-face {{ font-family: "{family}"; font-weight: {weight}; font-display: block; '
               f'src: url(data:font/ttf;base64,{data}) format("truetype"); }}')
open(os.path.join(HERE, "fonts.css"), "w").write("\n".join(css) + "\n")

src = open(os.path.join(APP, "src", "icons.rs")).read()
pairs = re.findall(r'pub const (\w+): &str = "\\u\{([0-9A-Fa-f]+)\}";', src)
js = ["// Generated by build-assets.py from crates/ternarywire-app/src/icons.rs. Do not edit.", "const ICON = {"]
js += [f'  {n}: "\\u{{{c.lower()}}}",' for n, c in pairs]
js.append("};")
open(os.path.join(HERE, "icons.js"), "w").write("\n".join(js) + "\n")
print(f"fonts.css: {len(faces)} faces · icons.js: {len(pairs)} icons")
